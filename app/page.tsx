import type { Metadata } from "next";
import { Suspense } from "react";
import { connection } from "next/server";
import { getDashboardData } from "@/lib/data/dashboard";
import { Header } from "@/components/dashboard/Header";
import { DistrictKpis } from "@/components/dashboard/DistrictKpis";
import { AlertsSection } from "@/components/dashboard/AlertsSection";
import { RedistributionPreview } from "@/components/dashboard/RedistributionPreview";
import { FacilityTable } from "@/components/dashboard/FacilityTable";
import { InventoryOverview } from "@/components/dashboard/InventoryOverview";
import { TransferManagement } from "@/components/dashboard/TransferManagement";
import { AgentInvestigationPanel } from "@/components/dashboard/AgentInvestigationPanel";
import { RealtimeAlertsListener } from "@/components/dashboard/RealtimeAlertsListener";
import { SimulationControlPanel } from "@/components/dashboard/SimulationControlPanel";

export const metadata: Metadata = {
  title: "District Overview — Smart Health Operations",
  description:
    "AI-assisted public healthcare operations and medicine supply-chain intelligence platform for Sehore District, Madhya Pradesh. Synthetic demo data only.",
};

function DashboardSkeleton() {
  return (
    <div className="min-h-screen bg-slate-50 flex flex-col animate-pulse">
      <div className="h-16 bg-white border-b border-slate-200" />
      <div className="max-w-7xl mx-auto w-full px-4 sm:px-6 lg:px-8 py-8 space-y-8">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
          {[1, 2, 3, 4].map((i) => (
            <div key={i} className="h-28 bg-white rounded-xl border border-slate-200" />
          ))}
        </div>
        <div className="h-48 bg-white rounded-xl border border-slate-200" />
        <div className="h-72 bg-white rounded-xl border border-slate-200" />
      </div>
    </div>
  );
}

async function DashboardContent() {
  await connection();
  const data = await getDashboardData();

  return (
    <>
      <Header
        districtName={data.districtName}
        lastUpdated={data.timestamp}
      />

      <main className="flex-1 max-w-7xl w-full mx-auto px-4 sm:px-6 lg:px-8 py-5 space-y-4">
        {/* Interactive Simulation Control & Scripted Demo Storyline */}
        <section aria-labelledby="simulation-control-heading">
          <h2 id="simulation-control-heading" className="sr-only">Interactive Demo Simulation</h2>
          <SimulationControlPanel />
        </section>

        {/* District High-Level KPIs */}
        <section aria-labelledby="district-kpis-heading">
          <h2 id="district-kpis-heading" className="sr-only">District Operational KPIs</h2>
          <DistrictKpis metrics={data.metrics} />
        </section>

        {/* Operational Alerts & Immediate Shortages */}
        <section aria-labelledby="alerts-heading">
          <AlertsSection alerts={data.activeAlerts} />
        </section>

        {/* Redistribution Recommendations (Generated by Deterministic Engine) */}
        {data.redistributionPreviews.length > 0 && (
          <section aria-labelledby="redistribution-heading">
            <RedistributionPreview previews={data.redistributionPreviews} />
          </section>
        )}

        {/* AI Risk Investigation Assistant (Tool-Bounded) */}
        <section aria-labelledby="investigation-heading">
          <AgentInvestigationPanel
            targetFacilityId={data.targetInvestigation?.facilityId}
            targetMedicineId={data.targetInvestigation?.medicineId}
          />
        </section>

        {/* Transfer Proposals & Stock Movement Lifecycle */}
        <section aria-labelledby="transfers-heading">
          <TransferManagement transfers={data.pendingTransfers} />
        </section>

        {/* Facility Operational Status & Health Scores */}
        <section aria-labelledby="facilities-heading">
          <FacilityTable facilities={data.facilitiesList} />
        </section>

        {/* Medicine Inventory Overview & Days of Stock */}
        <section aria-labelledby="inventory-heading">
          <InventoryOverview inventory={data.inventoryList} />
        </section>
      </main>

      <footer className="border-t border-slate-200 bg-white py-6 text-center text-xs text-slate-500">
        <div className="max-w-7xl mx-auto px-4 space-y-1">
          <p className="font-semibold text-slate-700">
            Smart Health · Madhya Pradesh District Pilot Demonstration
          </p>
          <p>
            Pure Deterministic Engine · Supabase PostgreSQL · Next.js App Router · Simulated Data Model
          </p>
        </div>
      </footer>
    </>
  );
}

export default function DashboardPage() {
  return (
    <div className="min-h-screen bg-slate-50 flex flex-col font-sans text-slate-900">
      <Suspense fallback={<DashboardSkeleton />}>
        <DashboardContent />
      </Suspense>

      {/* Supabase Realtime Listener */}
      <RealtimeAlertsListener />
    </div>
  );
}
